/**
 * The in-page JavaScript the Rust node's browser embeds
 * (crates/pirc-node/src/browser/assets/, docs/development/historical-records.md):
 *
 * - `injected.js`: Playwright's injected script (aria snapshots, `aria-ref`
 *   and text selectors, actionability), copied out of the pinned
 *   playwright-core bundle, as spike A's extract.ts did.
 * - `websocket-mock.js`: Playwright's main-world WebSocket replacement, the
 *   in-page half of `context.routeWebSocket`.
 * - `page-markdown.js`, `password-values.js`, `sensitive-field.js`: the TS
 *   node's own in-page helpers (node/browser-extract.ts, node/browser.ts), as
 *   the source text Playwright's `evaluate` sends for them.
 * - `PLAYWRIGHT-LICENSE`, `PLAYWRIGHT-NOTICE`: playwright-core is Apache-2.0.
 *
 *   bun scripts/browser-assets.ts          write the assets
 *   bun scripts/browser-assets.ts --check  fail when they are stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pageMarkdown, passwordValues } from './browser/helpers.js';
import { sensitiveField } from './browser/sensitive-field.js';

const root = path.resolve(import.meta.dir, '..');
const playwright = path.join(root, 'node_modules/playwright-core');
const output = path.join(root, 'crates/pirc-node/src/browser/assets');

/**
 * The JS string literal of a generated source module of the bundle: esbuild
 * emits `// packages/playwright-core/src/<module>`, then `var <name>;` (a
 * minified name, renumbered between releases), then the module's body,
 * which assigns the literal to `<name>` before the next module begins.
 */
function literal(bundle: string, module: string): string {
  const escaped = module.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
  const header = new RegExp(`^// packages/playwright-core/src/${escaped}\nvar (\\w+);\n`, 'm').exec(
    bundle,
  );
  if (!header) throw new Error(`${module} (with its var) not found in playwright-core`);
  const name = header[1]!;
  const body = header.index + header[0].length;
  const next = bundle.indexOf('\n// packages/', body);
  const assignment = new RegExp(`\\b${name} = `, 'g');
  assignment.lastIndex = body;
  const found = assignment.exec(bundle);
  if (!found || (next >= 0 && found.index > next))
    throw new Error(`${module}: no assignment to ${name} in the module`);
  const start = found.index + found[0].length;
  const quote = bundle[start];
  if (quote !== "'" && quote !== '`') throw new Error(`${name}: not a string literal`);
  let end = start + 1;
  while (bundle[end] !== quote) end += bundle[end] === '\\' ? 2 : 1;
  const text = bundle.slice(start, end + 1);
  if (quote === '`' && /(^|[^\\])\$\{/.test(text))
    throw new Error(`${name}: template has substitutions`);
  return (0, eval)(text) as string;
}

const { version } = JSON.parse(readFileSync(path.join(playwright, 'package.json'), 'utf8')) as {
  version: string;
};
const bundle = readFileSync(path.join(playwright, 'lib/coreBundle.js'), 'utf8');
const banner = (what: string) =>
  `// ${what}\n// Generated by scripts/browser-assets.ts; do not edit.\n`;
const pw = (what: string) =>
  banner(
    `${what} from playwright-core ${version} (Apache-2.0, Copyright (c) Microsoft Corporation; see PLAYWRIGHT-LICENSE and PLAYWRIGHT-NOTICE).`,
  );
const helper = (what: string, fn: (...args: never[]) => unknown) =>
  `${banner(`${what}, as Playwright's evaluate sends it.`)}${fn.toString()}\n`;

const files: Record<string, string> = {
  'injected.js': `${pw('The injected script (generated/injectedScriptSource.ts)')}${literal(bundle, 'generated/injectedScriptSource.ts')}\n`,
  'websocket-mock.js': `${pw('The WebSocket mock (generated/webSocketMockSource.ts)')}${literal(bundle, 'generated/webSocketMockSource.ts')}\n`,
  'page-markdown.js': helper(
    'pageMarkdown (apps/gateway/src/node/browser-extract.ts)',
    pageMarkdown,
  ),
  'password-values.js': helper(
    'passwordValues (apps/gateway/src/node/browser-extract.ts)',
    passwordValues,
  ),
  'sensitive-field.js': helper('sensitiveField (apps/gateway/src/node/browser.ts)', sensitiveField),
  'PLAYWRIGHT-LICENSE': readFileSync(path.join(playwright, 'LICENSE'), 'utf8'),
  'PLAYWRIGHT-NOTICE': readFileSync(path.join(playwright, 'NOTICE'), 'utf8'),
};

if (process.argv.includes('--check')) {
  const stale = Object.entries(files).filter(([name, text]) => {
    try {
      return readFileSync(path.join(output, name), 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(
      `${stale.map(([name]) => path.join(path.relative(root, output), name)).join(', ')} stale; run bun scripts/browser-assets.ts (playwright-core ${version})`,
    );
    process.exit(1);
  }
} else {
  for (const [name, text] of Object.entries(files)) writeFileSync(path.join(output, name), text);
  console.log(
    `${path.relative(root, output)}: playwright-core ${version}, ${Object.entries(files)
      .map(([name, text]) => `${name} ${text.length}`)
      .join(', ')}`,
  );
}
