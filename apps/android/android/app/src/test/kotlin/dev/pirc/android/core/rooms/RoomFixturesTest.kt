package dev.pirc.android.core.rooms

import dev.pirc.android.core.PircJson
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonArray
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * The shared room cases in `fixtures/timeline/rooms`, generated by the web
 * client (`apps/web/src/lib/rooms-fixtures.test.ts`): this port must turn the
 * same load and events into the same view and ask for the same follow-ups.
 */
class RoomFixturesTest {
    private val dir = File(System.getProperty("pirc.fixtures") ?: "../../../../fixtures", "timeline/rooms")

    @Test
    fun matchesTheWebClient() {
        val files = dir.listFiles { file -> file.extension == "json" }.orEmpty().sortedBy { it.name }
        assertTrue("fewer than two room fixtures in $dir", files.size > 1)
        for (file in files) {
            val fixture = PircJson.parseToJsonElement(file.readText()) as JsonObject
            val expected = fixture["expected"] as JsonObject
            val typingAt = fixture["typingAt"].long
            var view = loaded(fixture)
            assertEquals("${file.name}: after loading", expected["afterLoad"], project(view, typingAt))
            val effects = mutableListOf<RoomEffect>()
            for (event in fixture["events"] as JsonArray) {
                val reduced = view.reduce(event as JsonObject)
                view = reduced.view
                effects += reduced.effects
            }
            assertEquals("${file.name}: after the events", expected["afterEvents"], project(view, typingAt))
            assertEquals("${file.name}: effects", expected["effects"], JsonArray(effects.map(::effect)))
        }
    }

    @Test
    fun aLongWorkerLineIsCutAndAnEmptyOneSaysNothing() {
        fun tool(summary: String) = PircJson.parseToJsonElement(
            """{"id":"t","threadId":"x","seq":1,"speaker":"worker:s","kind":"tool","body":{"summary":${JsonPrimitive(summary)}},"createdAt":5,"updatedAt":null}""",
        ) as JsonObject
        val long = activityOf(tool("\n  " + "a".repeat(130) + "\nsecond"))!!
        assertEquals(120, long.text.length)
        assertTrue(long.text.endsWith("…"))
        assertEquals(5L, long.at)
        assertNull(activityOf(tool("  \n ")))
        // Only workers' messages say what a worker does.
        val face = JsonObject(tool("hello") + ("speaker" to JsonPrimitive("face:host")))
        assertNull(activityOf(face))
    }

    private fun loaded(fixture: JsonObject) = RoomsView(
        user = fixture["user"].str!!,
        currentId = fixture["open"].str!!,
        rooms = objects(fixture["rooms"]),
        messages = objects(fixture["messages"]),
        pinned = objects(fixture["pinned"]),
        faces = objects(fixture["faces"]),
        threadId = fixture["thread"].str,
        threadMessages = objects(fixture["threadMessages"]),
    )

    private fun objects(value: Any?) = (value as? JsonArray).orEmpty().map { it as JsonObject }

    private fun effect(effect: RoomEffect) = buildJsonObject {
        when (effect) {
            RoomEffect.RefreshList -> put("type", "refresh_list")
            is RoomEffect.RefreshRoom -> {
                put("type", "refresh_room")
                put("roomId", effect.roomId)
            }
            RoomEffect.MarkRead -> put("type", "mark_read")
            RoomEffect.RefreshThreadWorkers -> put("type", "refresh_thread_workers")
        }
    }

    private fun orNull(value: String?) = value?.let(::JsonPrimitive) ?: JsonNull

    /** Mirrors `project` in `apps/web/src/lib/rooms-fixtures.test.ts`. */
    private fun project(view: RoomsView, typingAt: Long?) = buildJsonObject {
        put("rooms", buildJsonArray {
            view.rooms.forEach { room ->
                add(buildJsonObject {
                    put("id", room.id)
                    put("lastSeq", room["lastSeq"] ?: JsonNull)
                    put("unread", room["unread"] ?: JsonNull)
                    put("movedFromRoomId", room["movedFromRoomId"] ?: JsonNull)
                })
            }
        })
        put("open", view.currentId)
        put("messages", buildJsonArray {
            view.messages.forEach { message ->
                add(buildJsonObject {
                    put("seq", message["seq"] ?: JsonNull)
                    put("speaker", message["speaker"] ?: JsonNull)
                    put("user", message["user"] ?: JsonNull)
                    put("kind", message["kind"] ?: JsonNull)
                    put("text", orNull(message["body"]["text"].str))
                    put("pinned", message["pinnedAt"] != null && message["pinnedAt"] != JsonNull)
                })
            }
        })
        put("pinned", JsonArray(view.pinned.map { JsonPrimitive(it.id) }))
        // Without a `typingAt` the web compares with undefined: nobody types.
        put("typing", JsonArray(
            if (typingAt == null) emptyList()
            else view.typing[view.currentId].orEmpty()
                .filter { (who, until) -> who != view.user && until > typingAt }
                .keys.map(::JsonPrimitive),
        ))
        put("thinking", JsonObject(view.thinking.mapValues { (_, faces) -> JsonArray(faces.map(::JsonPrimitive)) }))
        put("faces", JsonArray(view.faces.map { face ->
            buildJsonObject {
                put("id", face.id)
                put("name", face["name"] ?: JsonNull)
            }
        }))
        put("facePresence", JsonObject(view.facePresence.mapValues { (_, presence) ->
            buildJsonObject {
                put("state", presence["state"] ?: JsonNull)
                put("roomId", orNull(presence["roomId"].str))
                put("line", orNull(presence["line"].str))
            }
        }))
        put("thread", orNull(view.threadId))
        put("threadMessages", buildJsonArray {
            view.threadMessages.forEach { message ->
                add(buildJsonObject {
                    put("seq", message["seq"] ?: JsonNull)
                    put("speaker", message["speaker"] ?: JsonNull)
                    put("kind", message["kind"] ?: JsonNull)
                    put("text", orNull(message["body"]["text"].str ?: message["body"]["summary"].str))
                })
            }
        })
        put("threadActivity", JsonObject(view.threadActivity.mapValues { (_, activity) -> JsonPrimitive(activity.text) }))
        put("loopsRevision", view.loopsRevision)
        put("wakesRevision", view.wakesRevision)
    }
}
