#!/usr/bin/env python3
"""Generate bounded document encoding tables from pinned WHATWG source data.

No network is used. Upstream data and its full license are retained in vendor/.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
VENDOR = ROOT / "vendor/whatwg-encoding-20240918"
OUTPUT = ROOT / "document_encoding_data.js"


def generate() -> str:
    provenance = json.loads((VENDOR / "provenance.json").read_text())
    for name, item in provenance["files"].items():
        if hashlib.sha256((VENDOR / name).read_bytes()).hexdigest() != item["sha256"]:
            raise ValueError("Vendored encoding checksum mismatch: " + name)
    labels = {}
    for group in json.loads((VENDOR / "encodings.json").read_text()):
        for encoding in group["encodings"]:
            for label in encoding["labels"]:
                labels[label] = encoding["name"].lower()
    table = [0] * (126 * 157)
    for line in (VENDOR / "index-big5.txt").read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        pointer, point, *_ = line.split()
        table[int(pointer)] = int(point, 16)
    # Zero denotes a missing pointer: the upstream table contains no U+0000.
    lines = ["/* Generated by generate_document_encoding_data.py; do not edit.",
             " * WHATWG Encoding Standard, index date 2024-09-18.",
             " * Source portions: BSD-3-Clause; see vendored LICENSE and provenance. */",
             "function createDocumentEncodingData() {", "  'use strict';",
             "  const encodingLabels = Object.freeze(" + json.dumps(labels, sort_keys=True, separators=(",", ":")) + ");",
             "  let table;", "  function big5CodePoint(pointer) {",
             "    if (!Number.isInteger(pointer) || pointer < 0 || pointer >= 19782) return null;",
             "    if (!table) table = new Uint32Array(["];
    for index in range(0, len(table), 48):
        lines.append("      " + ",".join(str(value) for value in table[index:index+48]) + ",")
    lines += ["    ]);", "    return table[pointer] || null;", "  }",
              "  return { encodingLabels, big5CodePoint };", "}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if OUTPUT.read_text() != content:
            raise SystemExit("document_encoding_data.js is stale; run this generator")
        print("Encoding data checksums and generated source match.")
    else:
        OUTPUT.write_text(content)
        print("Wrote " + str(OUTPUT))


if __name__ == "__main__":
    main()
