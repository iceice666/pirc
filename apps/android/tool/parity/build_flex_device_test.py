"""Generate native-device Flex tests from the reviewed host test and Chromium corpus."""
from pathlib import Path
import hashlib
import json

mobile=Path(__file__).resolve().parents[2]
fixture_path=mobile.parent.parent/'fixtures/mobile-parity/html-flex-layout.json'
fixture=fixture_path.read_bytes()
cases=json.loads(fixture)
source=(mobile/'test/html_flex_layout_test.dart').read_text()
source=source.replace("import 'dart:io';\n",'')
source=source.replace("import 'live_test.dart' show theme;", "import 'package:pirc_mobile/theme.dart';\nimport 'package:integration_test/integration_test.dart';")
source=source.replace('void main() {', 'void main() async {\n  IntegrationTestWidgetsFlutterBinding.ensureInitialized();\n  final theme = await PircTheme.load();',1)
start=source.index('  final fixture =')
end=source.index("  for (final c in fixture['cases'] as List)",start)
encoded=json.dumps(cases,separators=(',',':'),ensure_ascii=False)
assert "'''" not in encoded
source=source[:start]+"  final fixture = jsonDecode(r'''"+encoded+"''') as Map;\n"+source[end:]
header='// Generated by tool/parity/build_flex_device_test.py.\n// Dedicated AVD: 1200x1000 logical viewport, density 160.\n// Fixture SHA256: '+hashlib.sha256(fixture).hexdigest()+'\n'
(mobile/'integration_test/html_flex_test.dart').write_text(header+source)
print('Generated',len(cases['cases'])*2+3,'native document Flex cases')
