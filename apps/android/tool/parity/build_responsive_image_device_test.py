"""Generate native Android PNG selection/geometry checks from Chrome fixtures."""
from pathlib import Path
import json
root = Path(__file__).resolve().parents[4]
fixture = json.loads((root / 'fixtures/mobile-parity/html-responsive-images.json').read_text())
source = (root / 'apps/android/test/responsive_image_oracle_test.dart').read_text()
start = source.index('  final fixture =')
end = source.index('  final assets =', start)
encoded = json.dumps(fixture, ensure_ascii=False, separators=(',', ':'))
assert "'''" not in encoded
source = source[:start] + "  IntegrationTestWidgetsFlutterBinding.ensureInitialized();\n  final fixture = jsonDecode(r'''" + encoded + "''') as Map;\n" + source[end:]
start = source.index("    test('Chrome responsive source")
end = source.index('    for (final brightness', start)
source = source[:start] + source[end:]
source = source.replace("import 'dart:io';\n", "import 'dart:async';\n")
source = source.replace("import 'package:html/parser.dart' as html;", "import 'package:html/parser.dart' as html;\nimport 'package:integration_test/integration_test.dart';\nimport 'package:pirc_mobile/theme.dart';\nimport 'package:pirc_mobile/live/gateway.dart';")
source = source.replace("import 'package:pirc_mobile/rendering/html_responsive_image.dart';\n", '')
source = source.replace("import 'live_test.dart' show FakeGateway, theme;\n", '')
source = source.replace("import 'markdown_image_test.dart' show waitImage;\n", '')
source = source.replace('        tester.view.physicalSize = Size(width, height);\n        tester.view.devicePixelRatio = 1;\n        addTearDown(tester.view.reset);', '        final theme = await PircTheme.load();')
source = source.replace('data: MediaQuery.of(context).copyWith(devicePixelRatio: dpr),', 'data: MediaQuery.of(context).copyWith(devicePixelRatio: dpr, size: Size(width, height)),')
source = source.replace('body: NativeFetchedDocumentView(', 'body: SizedBox(width: width, height: height, child: NativeFetchedDocumentView(')
source = source.replace('onSubmit: (_) {},\n                ),', 'onSubmit: (_) {},\n                )),')
source += '''
// Fixtures provide exact bytes; Android still decodes and lays out the PNG.
// This harness does not claim real Gateway authentication or remote transport.
class FakeGateway extends Gateway {
  final stream = StreamController<Json>.broadcast(sync: true);
  @override
  Stream<Json> get events => stream.stream;
  Future<dynamic> Function(String, Json)? handler;
  @override
  Future<dynamic> call(String method, [Json args = const {}]) async => handler!(method, args);
}
Future<void> waitImage(WidgetTester tester, bool Function() ready) async {
  for (var i = 0; i < 100 && !ready(); i++) {
    await tester.runAsync(() => Future<void>.delayed(const Duration(milliseconds: 10)));
    await tester.pump();
  }
  expect(ready(), isTrue);
  expect(tester.takeException(), isNull);
}
'''
(root / 'apps/android/integration_test/responsive_images_test.dart').write_text('// Generated by tool/parity/build_responsive_image_device_test.py.\n// Owned emulator viewport must fit 1024x800 logical pixels.\n' + source)
print(f'Generated {len(fixture["fixtures"])*2} Android responsive image comparisons')
