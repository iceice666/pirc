import 'dart:convert';
import 'dart:io';

// Run from apps/android: dart run tool/generate_l10n.dart
void main() {
  final en = Map<String, String>.from(
    jsonDecode(File('lib/l10n/en.json').readAsStringSync()) as Map,
  );
  final zh = Map<String, String>.from(
    jsonDecode(File('lib/l10n/zh-TW.json').readAsStringSync()) as Map,
  );
  final tokens = RegExp(r'\{\d+\}');
  String parameters(String value) =>
      (tokens.allMatches(value).map((m) => m[0]!).toList()..sort()).join(',');
  if (en.length != zh.length || en.keys.any((key) => !zh.containsKey(key))) {
    throw StateError('Locale key mismatch');
  }
  for (final key in en.keys) {
    if (parameters(key) != parameters(en[key]!) ||
        parameters(en[key]!) != parameters(zh[key]!)) {
      throw StateError('Locale parameters differ: $key');
    }
  }
  String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
  final output = StringBuffer(
    '// Generated by tool/generate_l10n.dart. Edit the JSON catalogs.\n',
  );
  for (final (name, map) in [
    ('englishMessages', en),
    ('traditionalChineseMessages', zh),
  ]) {
    output.writeln('const $name = <String, String>{');
    for (final entry in map.entries) {
      output.writeln('  ${literal(entry.key)}: ${literal(entry.value)},');
    }
    output.writeln('};');
  }
  File('lib/l10n/catalogs.g.dart').writeAsStringSync(output.toString());
}
