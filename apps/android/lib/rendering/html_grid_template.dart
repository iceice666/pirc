import 'dart:math' as math;

import 'package:csslib/visitor.dart' as css;

/// One explicitly supported CSS grid column track.
///
/// Track breadths are stored as fixed pixels, a percentage of the container,
/// or a fraction of the remaining space. A fractional track may also have a
/// pixel floor when it came from `minmax(<length>, <positive-fr>)`.
class NativeGridTrack {
  const NativeGridTrack._({
    required this.fixedPx,
    required this.fixedPercent,
    required this.fraction,
    required this.minimumPx,
    required this.isFixedPixel,
  });

  const NativeGridTrack.pixels(double value)
    : this._(
        fixedPx: value,
        fixedPercent: 0,
        fraction: 0,
        minimumPx: 0,
        isFixedPixel: true,
      );

  const NativeGridTrack.percent(double value)
    : this._(
        fixedPx: 0,
        fixedPercent: value,
        fraction: 0,
        minimumPx: 0,
        isFixedPixel: false,
      );

  const NativeGridTrack.fraction(double value, {double minimumPx = 0})
    : this._(
        fixedPx: 0,
        fixedPercent: 0,
        fraction: value,
        minimumPx: minimumPx,
        isFixedPixel: false,
      );

  final double fixedPx;
  final double fixedPercent;
  final double fraction;
  final double minimumPx;
  final bool isFixedPixel;

  @override
  bool operator ==(Object other) =>
      other is NativeGridTrack &&
      other.fixedPx == fixedPx &&
      other.fixedPercent == fixedPercent &&
      other.fraction == fraction &&
      other.minimumPx == minimumPx &&
      other.isFixedPixel == isFixedPixel;

  @override
  int get hashCode =>
      Object.hash(fixedPx, fixedPercent, fraction, minimumPx, isFixedPixel);
}

/// The subset of `grid-template-columns` understood by the native renderer.
///
/// Parsing consumes csslib's expression tree. Unsupported CSS constructs
/// return `null`, allowing callers to use their normal layout fallback.
class NativeGridTemplate {
  NativeGridTemplate._(
    List<_TemplateTrack> tracks, {
    required this.collapseEmpty,
  }) : _tracks = List.unmodifiable(tracks);

  static const int _maximumTrackCount = 64;
  static const int _maximumRepeatNesting = 16;

  final List<_TemplateTrack> _tracks;

  /// Whether tracks generated by `repeat(auto-fit, ...)` collapse when empty.
  final bool collapseEmpty;

  /// Parses fixed pixel, percentage, and fractional tracks, plus the supported
  /// `minmax` and `repeat` forms. This deliberately rejects the rest of the
  /// CSS grid track grammar.
  static NativeGridTemplate? parse(css.Expression? expression) {
    if (expression == null) return null;
    final expressions = expression is css.Expressions
        ? expression.expressions
        : <css.Expression>[expression];
    final tracks = _parseTrackList(expressions);
    if (tracks == null || tracks.isEmpty) return null;

    final autoTracks = tracks.whereType<_AutoRepeatTrack>().toList();
    // Adjacent explicit tracks need distinct empty-track/gutter treatment.
    // Until that placement is implemented, accept only standalone auto-repeat.
    if (autoTracks.length > 1 ||
        (autoTracks.isNotEmpty && tracks.length != 1)) {
      return null;
    }
    final fixedCount = tracks.whereType<_FixedTrack>().length;
    if (fixedCount > _maximumTrackCount ||
        (autoTracks.isNotEmpty && fixedCount >= _maximumTrackCount)) {
      return null;
    }
    return NativeGridTemplate._(
      tracks,
      collapseEmpty: autoTracks.isNotEmpty && autoTracks.single.collapseEmpty,
    );
  }

  /// Expands integer and responsive repeats into concrete tracks.
  List<NativeGridTrack> expand(double containerWidth, double columnGap) {
    final autoIndex = _tracks.indexWhere((track) => track is _AutoRepeatTrack);
    if (autoIndex < 0) {
      return [for (final track in _tracks) (track as _FixedTrack).track];
    }

    final auto = _tracks[autoIndex] as _AutoRepeatTrack;
    final fixed = _tracks.whereType<_FixedTrack>().map((track) => track.track);
    final fixedTracks = fixed.toList();
    final width = containerWidth.isFinite
        ? math.max(0.0, containerWidth).toDouble()
        : 0.0;
    final gap = columnGap.isFinite ? math.max(0.0, columnGap).toDouble() : 0.0;

    // Reserve the explicit tracks' fixed and minimum widths before counting
    // responsive tracks. Percentages are based on the container width.
    final fixedWidth = fixedTracks.fold<double>(
      0,
      (sum, track) =>
          sum +
          track.fixedPx +
          width * track.fixedPercent / 100 +
          track.minimumPx,
    );
    final fixedCount = fixedTracks.length;
    final room = width - fixedWidth - gap * math.max(0, fixedCount - 1);
    final denominator = auto.track.minimumPx + gap;
    final desiredCount = denominator > 0
        ? ((room + gap) / denominator).floor()
        : _maximumTrackCount;
    final maximumCount = math.max(1, _maximumTrackCount - fixedCount).toInt();
    final count = desiredCount.clamp(1, maximumCount).toInt();

    final result = <NativeGridTrack>[];
    for (var index = 0; index < _tracks.length; index++) {
      final track = _tracks[index];
      if (track is _FixedTrack) {
        result.add(track.track);
      } else {
        result.addAll(List.filled(count, auto.track));
      }
    }
    return result;
  }

  static List<_TemplateTrack>? _parseTrackList(
    List<css.Expression> expressions, {
    int depth = 0,
    bool allowAutoRepeat = true,
  }) {
    if (depth > _maximumRepeatNesting || expressions.isEmpty) return null;
    final tracks = <_TemplateTrack>[];
    for (final expression in expressions) {
      if (expression is css.OperatorComma ||
          expression is css.OperatorSlash ||
          expression is css.OperatorPlus ||
          expression is css.OperatorMinus) {
        return null;
      }

      if (expression is css.FunctionTerm) {
        final name = expression.text.toLowerCase();
        if (name == 'minmax') {
          final track = _parseMinmax(expression);
          if (track == null) return null;
          tracks.add(_FixedTrack(track));
        } else if (name == 'repeat') {
          final expanded = _parseRepeat(
            expression,
            depth: depth,
            allowAutoRepeat: allowAutoRepeat,
          );
          if (expanded == null) return null;
          tracks.addAll(expanded);
        } else {
          return null;
        }
      } else {
        final track = _parseSimpleTrack(expression);
        if (track == null) return null;
        tracks.add(_FixedTrack(track));
      }

      if (tracks.length > _maximumTrackCount) return null;
    }

    if (tracks.whereType<_AutoRepeatTrack>().length > 1) return null;
    return tracks;
  }

  static List<_TemplateTrack>? _parseRepeat(
    css.FunctionTerm function, {
    required int depth,
    required bool allowAutoRepeat,
  }) {
    final arguments = _functionArguments(function);
    if (arguments.length != 2 ||
        arguments.any((argument) => argument.isEmpty)) {
      return null;
    }
    final count = arguments.first;
    if (count.length != 1) return null;

    final repeatTracks = arguments.last;
    final countTerm = count.single;
    if (countTerm is css.LiteralTerm) {
      final keyword = countTerm.text.toLowerCase();
      if (keyword == 'auto-fit' || keyword == 'auto-fill') {
        if (!allowAutoRepeat || repeatTracks.length != 1) return null;
        final expression = repeatTracks.single;
        if (expression is! css.FunctionTerm ||
            expression.text.toLowerCase() != 'minmax') {
          return null;
        }
        final track = _parseMinmax(expression);
        if (track == null || track.fraction <= 0 || track.minimumPx <= 0) {
          return null;
        }
        return [_AutoRepeatTrack(track, collapseEmpty: keyword == 'auto-fit')];
      }
    }

    final repeatCount = _positiveInteger(countTerm);
    if (repeatCount == null || repeatCount > _maximumTrackCount) return null;
    final nested = _parseTrackList(
      repeatTracks,
      depth: depth + 1,
      allowAutoRepeat: false,
    );
    if (nested == null ||
        nested.isEmpty ||
        nested.any((track) => track is _AutoRepeatTrack)) {
      return null;
    }
    if (nested.length * repeatCount > _maximumTrackCount) return null;
    return [for (var i = 0; i < repeatCount; i++) ...nested];
  }

  static NativeGridTrack? _parseMinmax(css.FunctionTerm function) {
    final arguments = _functionArguments(function);
    if (arguments.length != 2 ||
        arguments[0].length != 1 ||
        arguments[1].length != 1) {
      return null;
    }
    final minimum = _lengthPixels(arguments[0].single);
    final maximum = _positiveFraction(arguments[1].single);
    if (minimum == null || maximum == null) return null;
    return NativeGridTrack.fraction(maximum, minimumPx: minimum);
  }

  static NativeGridTrack? _parseSimpleTrack(css.Expression expression) {
    if (expression is css.LengthTerm && expression.unitToString() == 'px') {
      final value = _numberValue(expression.value);
      return value != null && value >= 0 ? NativeGridTrack.pixels(value) : null;
    }
    if (expression is css.NumberTerm) {
      final value = _numberValue(expression.value);
      // CSS allows a unitless zero as a length.
      return value == 0 ? const NativeGridTrack.pixels(0) : null;
    }
    if (expression is css.PercentageTerm) {
      final value = _numberValue(expression.value);
      return value != null && value >= 0
          ? NativeGridTrack.percent(value)
          : null;
    }
    if (expression is css.FractionTerm) {
      final value = _numberValue(expression.value);
      return value != null && value > 0
          ? NativeGridTrack.fraction(value)
          : null;
    }
    return null;
  }

  static double? _lengthPixels(css.Expression expression) {
    if (expression is css.LengthTerm && expression.unitToString() == 'px') {
      final value = _numberValue(expression.value);
      return value != null && value >= 0 ? value : null;
    }
    if (expression is css.NumberTerm && _numberValue(expression.value) == 0) {
      return 0;
    }
    return null;
  }

  static double? _positiveFraction(css.Expression expression) {
    if (expression is! css.FractionTerm) return null;
    final value = _numberValue(expression.value);
    return value != null && value > 0 ? value : null;
  }

  static int? _positiveInteger(css.Expression expression) {
    if (expression is! css.NumberTerm) return null;
    final value = _numberValue(expression.value);
    if (value == null || value <= 0 || value != value.roundToDouble()) {
      return null;
    }
    return value.toInt();
  }

  static double? _numberValue(Object? value) {
    if (value is! num) return null;
    final result = value.toDouble();
    return result.isFinite ? result : null;
  }

  static List<List<css.Expression>> _functionArguments(
    css.FunctionTerm function,
  ) {
    final collector = _FunctionParametersCollector();
    function.visit(collector);
    final parameters = collector.parameters[function];
    if (parameters == null) return const [];

    final result = <List<css.Expression>>[<css.Expression>[]];
    for (final parameter in parameters) {
      if (parameter is css.OperatorComma) {
        result.add(<css.Expression>[]);
      } else {
        result.last.add(parameter);
      }
    }
    return result;
  }
}

sealed class _TemplateTrack {}

final class _FixedTrack extends _TemplateTrack {
  _FixedTrack(this.track);

  final NativeGridTrack track;
}

final class _AutoRepeatTrack extends _TemplateTrack {
  _AutoRepeatTrack(this.track, {required this.collapseEmpty});

  final NativeGridTrack track;
  final bool collapseEmpty;
}

/// csslib keeps FunctionTerm's argument list private. Its visitor exposes each
/// nested Expressions node, so collect the original AST arguments without
/// reparsing or splitting the serialized CSS text.
class _FunctionParametersCollector extends css.Visitor {
  final Map<css.FunctionTerm, List<css.Expression>> parameters = {};
  css.FunctionTerm? _activeFunction;

  @override
  dynamic visitFunctionTerm(css.FunctionTerm node) {
    final previous = _activeFunction;
    _activeFunction = node;
    super.visitFunctionTerm(node);
    _activeFunction = previous;
  }

  @override
  dynamic visitExpressions(css.Expressions node) {
    final function = _activeFunction;
    if (function != null && !parameters.containsKey(function)) {
      parameters[function] = List.unmodifiable(node.expressions);
    }
    super.visitExpressions(node);
  }
}
