import 'package:pirc_mobile/live/conversation_composer.dart';
import 'live_test.dart' show FakeGateway, theme;

Json dockFixture() => obj(
  jsonDecode(
    File('../../fixtures/mobile-parity/docks.json').readAsStringSync(),
  ),
);
Widget shell(
  LiveController c,
  TextEditingController text, {
  double scale = 1,
}) => MaterialApp(
  theme: theme.build(Brightness.light),
  builder: (context, child) => MediaQuery(
    data: MediaQuery.of(context).copyWith(textScaler: TextScaler.linear(scale)),
    child: child!,
  ),
  home: Scaffold(
    body: ListenableBuilder(
      listenable: c,
      builder: (context, _) => LayoutBuilder(
        builder: (context, bounds) => Column(
          children: [
            const Spacer(),
            ConstrainedBox(
              constraints: BoxConstraints(maxHeight: bounds.maxHeight),
              child: ConversationComposer(controller: c, text: text),
            ),
          ],
        ),
      ),
    ),
  ),
);
LiveController seeded(FakeGateway g) {
  final f = dockFixture();
  return LiveController(g)
    ..sessionId = 's'
    ..connection = 'live'
    ..control = {'held': true}
    ..state = obj(f['state'])
    ..models = rows(f['models']);
}

void main() {
  test(
    'goal and todo parsers match outputs generated by the pinned web source',
    () {
      final f = obj(
        jsonDecode(
          File(
            '../../fixtures/mobile-parity/dock-parsers.json',
          ).readAsStringSync(),
        ),
      );
      for (final row in rows(f['goals'])) {
        final g = parseGoalWidget(row['lines']);
        expect(
          g == null
              ? null
              : {
                  'phase': g.phase,
                  'disarmed': g.disarmed,
                  'rounds': g.rounds,
                  'objective': g.objective,
                  if (g.maxRounds != null) 'maxRounds': g.maxRounds,
                  if (g.reason != null) 'reason': g.reason,
                },
          row['expected'],
          reason: '${row['lines']}',
        );
      }
      for (final row in rows(f['todos'])) {
        final t = parseTodoWidget(row['lines']);
        expect(
          t == null
              ? null
              : {
                  'done': t.done,
                  'total': t.total,
                  'items': [
                    for (final i in t.items)
                      {
                        'status': i.status,
                        'text': i.text,
                        'blocked': i.blocked,
                        if (i.category != null) 'category': i.category,
                      },
                  ],
                },
          row['expected'],
          reason: '${row['lines']}',
        );
      }
      expect(
        parseGoalWidget(['GOAL · paused · 4/4', 'limit'])!.canResume,
        isFalse,
      );
      expect(
        parseGoalWidget([
          'GOAL · active · disarmed · 0/10',
          'restart',
        ])!.canResume,
        isTrue,
      );
      expect(
        parseGoalWidget(['GOAL · complete · 4/4', 'done'])!.running,
        isFalse,
      );
    },
  );
  testWidgets('goal stage actions are exclusive, bounded and require control', (
    t,
  ) async {
    t.view.devicePixelRatio = 1;
    t.view.physicalSize = const Size(390, 900);
    addTearDown(t.view.reset);
    final g = FakeGateway(), c = seeded(g), text = TextEditingController();
    await t.pumpWidget(shell(c, text));
    await t.pumpAndSettle();
    expect(find.text('Resume'), findsOneWidget);
    expect(find.text('Pause'), findsNothing);
    await t.tap(find.text('Resume'));
    await t.pumpAndSettle();
    expect(obj(g.calls.lastWhere((e) => e.$1 == 'command').$2['payload']), {
      'type': 'steer',
      'message': '/goal resume',
    });
    c.state = {
      ...c.state,
      'widgets': {
        'goal': ['GOAL · active · 3/12', 'Continue'],
      },
    };
    c.changed();
    await t.pumpAndSettle();
    expect(find.text('Pause'), findsOneWidget);
    expect(find.text('Resume'), findsNothing);
    c.control = {};
    c.changed();
    await t.pump();
    final before = g.calls.where((e) => e.$1 == 'command').length;
    await t.tap(find.text('Pause'));
    await t.pump();
    expect(g.calls.where((e) => e.$1 == 'command').length, before);
    c.state = {
      ...c.state,
      'widgets': {
        'goal': ['GOAL · paused · 12/12', 'Limit'],
      },
    };
    c.changed();
    await t.pump();
    expect(find.text('Pause'), findsNothing);
    expect(find.text('Resume'), findsNothing);
    expect(t.takeException(), isNull);
    await t.pumpWidget(const SizedBox());
    text.dispose();
    c.dispose();
    await g.stream.close();
  });
  testWidgets(
    'disclosures persist independently and queue resets after becoming empty',
    (t) async {
      t.view.devicePixelRatio = 1;
      t.view.physicalSize = const Size(390, 900);
      addTearDown(t.view.reset);
      final g = FakeGateway(), c = seeded(g), text = TextEditingController();
      final queue = rows(c.state['queue']);
      await t.pumpWidget(shell(c, text));
      await t.pumpAndSettle();
      expect(find.text('Waiting for a device to reconnect.'), findsNothing);
      await t.tap(find.byTooltip('Goal'));
      await t.pumpAndSettle();
      expect(find.text('Waiting for a device to reconnect.'), findsOneWidget);
      expect(c.preferences['goalExpanded'], true);
      await t.tap(find.byTooltip('Tasks'));
      await t.pumpAndSettle();
      expect(find.text('blocked'), findsOneWidget);
      await t.tap(find.byTooltip('Queued messages'));
      await t.pumpAndSettle();
      expect(
        find.byTooltip('Send now: ${queue.first['content']}'),
        findsNothing,
      );
      c.state = {...c.state, 'queue': []};
      c.changed();
      await t.pump();
      c.state = {...c.state, 'queue': queue};
      c.changed();
      await t.pump();
      expect(
        find.byTooltip('Send now: ${queue.first['content']}'),
        findsOneWidget,
      );
      await t.tap(find.byTooltip('Send now: ${queue.first['content']}'));
      await t.pumpAndSettle();
      expect(obj(g.calls.lastWhere((e) => e.$1 == 'command').$2['payload']), {
        'type': 'send_now',
        'queue': 'steering',
        'index': 0,
        'message': queue.first['content'],
      });
      await t.tap(find.text('Clear'));
      await t.pumpAndSettle();
      expect(obj(g.calls.lastWhere((e) => e.$1 == 'command').$2['payload']), {
        'type': 'clear_queue',
      });
      final saved = g.calls
          .where((e) => e.$1 == 'savePreferences')
          .map((e) => e.$2)
          .toList();
      expect(saved, [
        {'goalExpanded': true},
        {'todoExpanded': true},
      ]);
      expect(t.takeException(), isNull);
      await t.pumpWidget(const SizedBox());
      text.dispose();
      c.dispose();
      await g.stream.close();
    },
  );
  testWidgets('queue rows retain CSS height and the full send hit target', (
    t,
  ) async {
    t.view.devicePixelRatio = 1;
    addTearDown(t.view.reset);
    const longMessage = 'Please send this update after checking the build.';
    const shortMessage = 'Next.';
    for (final width in [390.0, 1024.0]) {
      t.view.physicalSize = Size(width, 900);
      final g = FakeGateway(), c = seeded(g), text = TextEditingController();
      c.state = {
        ...c.state,
        'widgets': <String, dynamic>{},
        'queue': [
          {
            'id': 'steer-0',
            'kind': 'steer',
            'index': 0,
            'content': longMessage,
          },
          {
            'id': 'follow-0',
            'kind': 'follow_up',
            'index': 0,
            'content': shortMessage,
          },
        ],
      };
      c.changed();
      await t.pumpWidget(shell(c, text));
      await t.pumpAndSettle();

      final firstRow = find.byKey(const ValueKey('composer-queue-row-0'));
      final secondRow = find.byKey(const ValueKey('composer-queue-row-1'));
      final expectedFirstHeight = width == 390 ? 52.0 : 32.0;
      expect(t.getSize(firstRow).height, expectedFirstHeight);
      expect(t.getSize(secondRow).height, 33);

      final overlap = find.byKey(
        const Key('composer-dock-negative-bottom-margin'),
      );
      final viewport = find
          .descendant(of: overlap, matching: find.byType(SingleChildScrollView))
          .first;
      expect(t.getSize(viewport).height - t.getSize(overlap).height, 1);

      final send = find.byTooltip('Send now: $longMessage');
      final rowRect = t.getRect(firstRow);
      final sendRect = t.getRect(send);
      expect(sendRect.size, const Size(26, 26));
      expect(sendRect.top - rowRect.top, 3);
      expect(sendRect.right, rowRect.right - 6);
      await t.tapAt(Offset(sendRect.right - 1, sendRect.bottom - 1));
      await t.pumpAndSettle();
      expect(obj(g.calls.lastWhere((e) => e.$1 == 'command').$2['payload']), {
        'type': 'send_now',
        'queue': 'steering',
        'index': 0,
        'message': longMessage,
      });
      expect(t.takeException(), isNull);
      await t.pumpWidget(const SizedBox());
      text.dispose();
      c.dispose();
      await g.stream.close();
    }
  });
  testWidgets('dock overlap is one pixel and empty docks stay zero height', (
    t,
  ) async {
    t.view.devicePixelRatio = 1;
    t.view.physicalSize = const Size(390, 900);
    addTearDown(t.view.reset);
    final g = FakeGateway(), c = seeded(g), text = TextEditingController();
    c.state = {...c.state, 'widgets': <String, dynamic>{}, 'queue': []};
    c.changed();
    await t.pumpWidget(shell(c, text));
    await t.pumpAndSettle();
    final overlap = find.byKey(
      const Key('composer-dock-negative-bottom-margin'),
    );
    final viewport = find.descendant(
      of: overlap,
      matching: find.byType(SingleChildScrollView),
    );
    expect(viewport, findsOneWidget);
    expect(t.getSize(viewport).height, 0);
    expect(t.getSize(overlap).height, 0);
    expect(t.takeException(), isNull);
    await t.pumpWidget(const SizedBox());
    text.dispose();
    c.dispose();
    await g.stream.close();
  });
  test(
    'rapid layout writes commit in order and do not discard unrelated preferences',
    () async {
      final g = FakeGateway(), c = seeded(g), gate = Completer<void>();
      c.preferences = {'appearance': 'dark'};
      g.handler = (m, a) async {
        if (m == 'savePreferences' && a['goalExpanded'] == true) {
          await gate.future;
        }
        return g.normal(m, a);
      };
      c.setDockExpanded('goalExpanded', true);
      c.setDockExpanded('goalExpanded', false);
      await Future<void>.delayed(Duration.zero);
      expect(g.calls.where((e) => e.$1 == 'savePreferences').length, 1);
      gate.complete();
      await Future<void>.delayed(Duration.zero);
      expect(
        g.calls
            .where((e) => e.$1 == 'savePreferences')
            .map((e) => e.$2['goalExpanded']),
        [true, false],
      );
      expect(c.preferences, {'appearance': 'dark', 'goalExpanded': false});
      c.dispose();
      await g.stream.close();
    },
  );
  for (final scale in [1.0, 2.0]) {
    testWidgets(
      'expanded dock stays scrollable above keyboard at scale $scale',
      (t) async {
        t.view.devicePixelRatio = 1;
        t.view.physicalSize = const Size(390, 844);
        t.view.viewInsets = const FakeViewPadding(bottom: 320);
        addTearDown(t.view.reset);
        final g = FakeGateway(),
            c = seeded(g),
            text = TextEditingController(text: 'Keep my draft');
        c.preferences = {'goalExpanded': true, 'todoExpanded': true};
        await t.pumpWidget(shell(c, text, scale: scale));
        await t.pumpAndSettle();
        expect(t.takeException(), isNull);
        final input = find.byType(TextField);
        expect(t.getBottomRight(input).dy, lessThanOrEqualTo(524));
        expect(text.text, 'Keep my draft');
        final scroller = find.ancestor(
          of: find.byType(ComposerDock),
          matching: find.byType(SingleChildScrollView),
        );
        expect(scroller, findsOneWidget);
        await t.drag(scroller, const Offset(0, -250));
        await t.pumpAndSettle();
        expect(t.takeException(), isNull);
        await t.pumpWidget(const SizedBox());
        text.dispose();
        c.dispose();
        await g.stream.close();
      },
    );
  }
  for (final width in [390.0, 768.0, 1024.0]) {
    testWidgets('expanded docks at $width with large text', (t) async {
      t.view.devicePixelRatio = 1;
      t.view.physicalSize = Size(width, 1100);
      addTearDown(t.view.reset);
      final g = FakeGateway(), c = seeded(g), text = TextEditingController();
      c.preferences = {'goalExpanded': true, 'todoExpanded': true};
      await t.pumpWidget(shell(c, text, scale: 2));
      await t.pumpAndSettle();
      expect(find.byType(ComposerDock), findsOneWidget);
      expect(t.takeException(), isNull);
      await t.pumpWidget(const SizedBox());
      text.dispose();
      c.dispose();
      await g.stream.close();
    });
  }
}
